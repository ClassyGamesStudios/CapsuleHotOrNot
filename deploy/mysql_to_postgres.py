"""
Convert the MySQL database (game_profiles_db) into one PostgreSQL .sql file.

    python deploy/mysql_to_postgres.py chon-export/game_profiles_db.pg.sql

The schema is read from information_schema, so new tables/columns are picked up
automatically. The output is a single transaction that DROPs and recreates every
table, so re-running it on the server replaces the Postgres copy with a fresh
snapshot. Identifiers keep their exact MySQL spelling (quoted, so mediaID stays
mediaID rather than folding to mediaid).

Type mapping: int/bigint as-is, tinyint -> smallint, float -> real,
double -> double precision, json -> jsonb, datetime -> timestamp,
AUTO_INCREMENT -> IDENTITY with the counter carried over, so the next id
handed out matches what MySQL would have used.
"""

import os
import sys
import datetime
import decimal

import pymysql

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import db  # noqa: E402  (reuses DB_CONFIG / DB_NAME, including .env overrides)

TYPE_MAP = {
    'int': 'integer',
    'bigint': 'bigint',
    'smallint': 'smallint',
    'tinyint': 'smallint',
    'float': 'real',
    'double': 'double precision',
    'json': 'jsonb',
    'datetime': 'timestamp',
    'timestamp': 'timestamp',
    'date': 'date',
    'text': 'text',
    'mediumtext': 'text',
    'longtext': 'text',
}


def q(name):
    return '"' + name.replace('"', '""') + '"'


def pg_type(col):
    dt = col['DATA_TYPE']
    if dt in ('varchar', 'char'):
        return f"{dt}({col['CHARACTER_MAXIMUM_LENGTH']})"
    if dt == 'decimal':
        return f"numeric({col['NUMERIC_PRECISION']},{col['NUMERIC_SCALE']})"
    if dt not in TYPE_MAP:
        raise SystemExit(f"No Postgres mapping for MySQL type {dt!r} "
                         f"({col['TABLE_NAME']}.{col['COLUMN_NAME']})")
    return TYPE_MAP[dt]


def pg_default(col):
    d = col['COLUMN_DEFAULT']
    if d is None:
        return ''
    if d.upper() in ('CURRENT_TIMESTAMP', 'CURRENT_TIMESTAMP()', 'NOW()'):
        return ' DEFAULT CURRENT_TIMESTAMP'
    if col['DATA_TYPE'] in TYPE_MAP and col['DATA_TYPE'] not in ('json', 'text'):
        if col['DATA_TYPE'] in ('date', 'datetime', 'timestamp'):
            return " DEFAULT '" + d.replace("'", "''") + "'"
        return f' DEFAULT {d}'
    return " DEFAULT '" + d.replace("'", "''") + "'"


def copy_value(v):
    """One field in COPY text format."""
    if v is None:
        return r'\N'
    if isinstance(v, bytes):
        v = v.decode('utf-8')
    if isinstance(v, datetime.datetime):
        v = v.isoformat(sep=' ')
    elif isinstance(v, (datetime.date, decimal.Decimal, int)):
        v = str(v)
    elif isinstance(v, float):
        v = repr(v)
    return (v.replace('\\', '\\\\').replace('\t', '\\t')
             .replace('\n', '\\n').replace('\r', '\\r'))


def main(out_path):
    cfg = dict(db.DB_CONFIG, database=db.DB_NAME, cursorclass=pymysql.cursors.DictCursor)
    conn = pymysql.connect(**cfg)
    cur = conn.cursor()
    # MySQL 8 caches AUTO_INCREMENT in information_schema for up to a day.
    cur.execute("SET SESSION information_schema_stats_expiry = 0")

    cur.execute("""SELECT TABLE_NAME, AUTO_INCREMENT FROM information_schema.TABLES
                   WHERE TABLE_SCHEMA=%s AND TABLE_TYPE='BASE TABLE' ORDER BY TABLE_NAME""",
                (db.DB_NAME,))
    tables = cur.fetchall()

    cur.execute("""SELECT * FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s
                   ORDER BY TABLE_NAME, ORDINAL_POSITION""", (db.DB_NAME,))
    columns = {}
    for c in cur.fetchall():
        columns.setdefault(c['TABLE_NAME'], []).append(c)

    cur.execute("""SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM information_schema.STATISTICS
                   WHERE TABLE_SCHEMA=%s ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX""", (db.DB_NAME,))
    indexes = {}
    for s in cur.fetchall():
        idx = indexes.setdefault(s['TABLE_NAME'], {}).setdefault(
            s['INDEX_NAME'], {'unique': not s['NON_UNIQUE'], 'cols': []})
        idx['cols'].append(s['COLUMN_NAME'])

    used_names = set()
    out = open(out_path, 'w', encoding='utf-8', newline='\n')
    w = out.write
    w(f"-- {db.DB_NAME} exported from MySQL {datetime.datetime.now():%Y-%m-%d %H:%M:%S}\n")
    w("\\set ON_ERROR_STOP on\nSET client_encoding = 'UTF8';\n"
      "SET client_min_messages = warning;\nBEGIN;\n\n")

    summary = []
    for t in tables:
        name = t['TABLE_NAME']
        cols = columns[name]
        tidx = indexes.get(name, {})
        defs = []
        identity_col = None
        for c in cols:
            line = f"  {q(c['COLUMN_NAME'])} {pg_type(c)}"
            if 'auto_increment' in c['EXTRA']:
                identity_col = c['COLUMN_NAME']
                line += ' GENERATED BY DEFAULT AS IDENTITY'
            else:
                line += pg_default(c)
            if c['IS_NULLABLE'] == 'NO':
                line += ' NOT NULL'
            defs.append(line)
        if 'PRIMARY' in tidx:
            defs.append(f"  PRIMARY KEY ({', '.join(q(c) for c in tidx['PRIMARY']['cols'])})")

        w(f"DROP TABLE IF EXISTS {q(name)} CASCADE;\n")
        w(f"CREATE TABLE {q(name)} (\n" + ',\n'.join(defs) + "\n);\n")

        # Postgres index names are schema-wide; MySQL's are per table
        # (e.g. both developer_profile and waitlist have a key called `email`).
        for iname, idx in tidx.items():
            if iname == 'PRIMARY':
                continue
            pg_name = iname if iname not in used_names and iname.startswith(('idx_', 'uniq_')) \
                else f"{name}_{iname}"
            used_names.add(pg_name)
            collist = ', '.join(q(c) for c in idx['cols'])
            if idx['unique']:
                w(f"ALTER TABLE {q(name)} ADD CONSTRAINT {q(pg_name)} UNIQUE ({collist});\n")
            else:
                w(f"CREATE INDEX {q(pg_name)} ON {q(name)} ({collist});\n")

        colnames = [c['COLUMN_NAME'] for c in cols]
        order = ', '.join(f"`{c}`" for c in tidx.get('PRIMARY', {'cols': colnames[:1]})['cols'])
        cur.execute(f"SELECT {', '.join(f'`{c}`' for c in colnames)} FROM `{name}` ORDER BY {order}")
        rows = cur.fetchall()
        w(f"COPY {q(name)} ({', '.join(q(c) for c in colnames)}) FROM stdin;\n")
        for r in rows:
            w('\t'.join(copy_value(r[c]) for c in colnames) + '\n')
        w("\\.\n")

        if identity_col and t['AUTO_INCREMENT']:
            # setval(..., n, false) => the next nextval() returns n, exactly MySQL's next id.
            w(f"DO $$ BEGIN PERFORM setval(pg_get_serial_sequence('{q(name)}', '{identity_col}'), "
              f"{t['AUTO_INCREMENT']}, false); END $$;\n")
        w("\n")
        summary.append((name, len(rows)))

    w("COMMIT;\n")
    w(''.join(f"ANALYZE {q(name)};\n" for name, _ in summary))
    out.close()
    conn.close()

    for name, n in summary:
        print(f"  {name:<20} {n:>6} rows")
    print(f"wrote {out_path} ({os.path.getsize(out_path) / 1e6:.1f} MB)")


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
